/// Nearest whole kilometer to one Julian light-year. Never use this as a local unit.
pub const KM_PER_LIGHT_YEAR: i64 = 9_460_730_472_581;

/// Absolute physical position, allowing system-boundary offsets smaller than a ly.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SpacePosition {
    pub x_km: i64,
    pub y_km: i64,
    pub z_km: i64,
}

impl SpacePosition {
    pub fn from_galaxy(position: GalaxyPosition) -> Result<Self, MovementError> {
        let convert = |value: i64| {
            value
                .checked_mul(KM_PER_LIGHT_YEAR)
                .ok_or(MovementError::Coordinates)
        };
        Ok(Self {
            x_km: convert(position.x)?,
            y_km: convert(position.y)?,
            z_km: convert(position.z)?,
        })
    }

    pub fn coordinates(self) -> [i64; 3] {
        [self.x_km, self.y_km, self.z_km]
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub enum MoveTarget {
    Body {
        system: SystemId,
        body: BodyId,
    },
    Local {
        system: SystemId,
        position: LocalPosition,
    },
    DeepSpace(GalaxyPosition),
    EnterSystem(SystemId),
    LeaveSystem(SystemId),
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum MovementMode {
    Local,
    Exit,
    DeepSpace,
    Entry,
}

impl MovementMode {
    pub fn label(self) -> &'static str {
        match self {
            Self::Local => "Local movement",
            Self::Exit => "System exit",
            Self::DeepSpace => "Deep-space movement",
            Self::Entry => "System entry",
        }
    }
}

/// Generated by the authority from current state. Clients submit intent, not this plan.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct MovementPlan {
    pub fleet: FleetId,
    pub origin: Location,
    pub destination: Location,
    pub mode: MovementMode,
    pub distance_km: u64,
    pub fuel_per_ship: u32,
    pub duration_ticks: u64,
    pub revision: u64,
    /// World tick the plan was computed at: bodies stood where their orbits put
    /// them then. Saves re-check plans at this tick.
    #[serde(default)]
    pub tick: u64,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum MovementError {
    Coordinates,
    OutsideGalaxy,
    WrongSpace,
    UnknownBody,
    StarCollision,
    /// The segment passes through a planet, moon, asteroid or station.
    BodyCollision,
    /// The waypoint lies inside a body's volume.
    InsideBody,
    AlreadyThere,
    InvalidRules,
}

impl std::fmt::Display for MovementError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Self::Coordinates => "Movement coordinates exceed supported limits.",
            Self::OutsideGalaxy => "Destination lies outside the galaxy cube.",
            Self::WrongSpace => "Exit to deep space before travelling between systems; enter a system before moving locally.",
            Self::UnknownBody => "Unknown destination body or missing trade port.",
            Self::StarCollision => "The route intersects the star's exclusion zone. Choose a waypoint around it.",
            Self::BodyCollision => "The route passes through a planet, moon or station. Choose a waypoint around it.",
            Self::InsideBody => "That point lies inside a planet, moon or station. Pick a point outside it, or the body itself.",
            Self::AlreadyThere => "The fleet is already at that destination.",
            Self::InvalidRules => "Invalid movement configuration or world bounds.",
        })
    }
}

